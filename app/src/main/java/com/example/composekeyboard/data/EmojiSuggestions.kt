    /**
     * Returns up to [maxCount] emojis matching the given typed prefix, exact
     * keyword matches first. Returns an empty list for prefixes shorter than
     * two characters or containing non-letters.
     */
    fun emojisFor(rawPrefix: String, maxCount: Int = 2): List<String> {
        val prefix = rawPrefix.lowercase()
        if (prefix.length < 2 || !prefix.all { it in 'a'..'z' || it == ' ' }) {
            return emptyList()
        }
        val results = ArrayList<String>(maxCount)
        keywords[prefix]?.let { exact ->
            for (emoji in exact) {
                if (results.size >= maxCount) return results
                results.add(emoji)
            }
        }
        for ((word, emojis) in keywords) {
            if (word.startsWith(prefix) && word != prefix) {
                for (emoji in emojis) {
                    if (results.size >= maxCount) return results
                    if (emoji !in results) results.add(emoji)
                }
            }
        }
        return results
    }
